#!/usr/bin/env python3
"""The one GitHub Actions workflow goatconf has: publish files/site to GitHub Pages.

CI stays local (tools/ci-local.sh). On the organiser's amendment of
2026-10-12 (sources/conversations/2026-10-12--org--public-repo-pages-goatconf-com.md)
one workflow may exist, and it only uploads files/site unchanged and
deploys it, on each push to main that changes files/site/. It builds and
checks nothing.

  build           write .github/workflows/publish-site.yml
  build --check   fail if it differs, or if any other workflow exists

Usage: python3 tools/pages.py build [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
WORKFLOWS = REPO / ".github" / "workflows"
NAME = "publish-site.yml"

WORKFLOW = """\
# Generated by files/tools/pages.py: edit it there, not here.
# The only workflow: upload files/site unchanged and deploy it to GitHub Pages.
# CI is local (files/tools/ci-local.sh) and runs before every push.
name: Publish the site

on:
  push:
    branches: [main]
    paths: ["files/site/**"]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: false

jobs:
  publish:
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: ${{ steps.deploy.outputs.page_url }}
    steps:
      - uses: actions/checkout@v5
      - uses: actions/configure-pages@v5
      - uses: actions/upload-pages-artifact@v4
        with:
          path: files/site
      - id: deploy
        uses: actions/deploy-pages@v4
"""


def problems() -> list[str]:
    out = []
    path = WORKFLOWS / NAME
    if not path.exists():
        out.append(f".github/workflows/{NAME} is missing: run python3 tools/pages.py build")
    elif path.read_text(encoding="utf-8") != WORKFLOW:
        out.append(f".github/workflows/{NAME} differs from tools/pages.py: run python3 tools/pages.py build")
    if WORKFLOWS.is_dir():
        for other in sorted(WORKFLOWS.iterdir()):
            if other.name != NAME:
                out.append(f".github/workflows/{other.name}: no workflow besides {NAME} is allowed (CI is local)")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        found = problems()
        for p in found:
            print(p)
        if not found:
            print(f".github/workflows/{NAME} is the only workflow, and current")
        return 1 if found else 0
    WORKFLOWS.mkdir(parents=True, exist_ok=True)
    (WORKFLOWS / NAME).write_text(WORKFLOW, encoding="utf-8")
    print(f"wrote .github/workflows/{NAME}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
